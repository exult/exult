#!/usr/bin/env python3
"""Regenerate embedded SPIR-V with glslangValidator (development-time only)."""
import os
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent


def strict_arithmetic(words):
    """Prevent vendor FMA contraction in the CPU-matching edge arithmetic."""
    decorations = []
    position = 5  # SPIR-V module header.
    insertion = None
    while position < len(words):
        count, opcode = words[position] >> 16, words[position] & 65535
        if insertion is None and 19 <= opcode <= 39:  # First type declaration.
            insertion = position
        if opcode in (129, 131, 133, 136, 142, 148):  # Floating arithmetic.
            # OpDecorate <result id> NoContraction; no new ids are allocated.
            decorations.extend([(3 << 16) | 71, words[position + 2], 42])
        position += count
    if decorations:
        assert insertion is not None
        words[insertion:insertion] = decorations
    return words


def main():
    parts = [
        "/*\n" + (ROOT / "LICENSE.scalefx").read_text() + "*/\n",
        "// Generated by compile_scalefx.py; edit scalefx-*.frag instead.\n",
        "#pragma once\n#include <cstdint>\nnamespace ScaleFX { namespace Shaders {\n",
    ]
    with tempfile.TemporaryDirectory() as temporary:
        for index in list(range(5)) + ["vertex"]:
            source = ROOT / ("scalefx.vert" if index == "vertex" else f"scalefx-{index}.frag")
            binary = Path(temporary) / f"{index}.spv"
            subprocess.run([
                os.environ.get("GLSLANG_VALIDATOR", "glslangValidator"),
                "-V", "--target-env", "vulkan1.0", "-o", str(binary), str(source),
            ], check=True)
            data = binary.read_bytes()
            words = strict_arithmetic(list(struct.unpack("<" + "I" * (len(data) // 4), data)))
            validator = os.environ.get("SPIRV_VAL") or shutil.which("spirv-val")
            if validator:
                binary.write_bytes(struct.pack("<" + "I" * len(words), *words))
                subprocess.run([validator, "--target-env", "vulkan1.0", str(binary)], check=True)
            parts.append(f"inline constexpr uint32_t pass{index}[] = {{\n")
            for start in range(0, len(words), 8):
                parts.append("    " + ",".join(f"0x{value:08x}" for value in words[start:start + 8]) + ",\n")
            parts.append("};\n")
    parts.append("}}\n")
    (ROOT / "scalefx_spirv.h").write_text("".join(parts))


if __name__ == "__main__":
    main()
